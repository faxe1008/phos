/// File offsets of the confirmed fields inside a base (extension-free) .NP3.
///
/// Verified against real samples (see `docs/np3-format.md`).
abstract final class Np3Offsets {
  static const int header = 0x00; // 16 bytes: magic+version+fmt
  static const int name = 0x18; // 20 bytes, ASCII, NUL-padded
  static const int sharpening = 0x52; // (b - 0x80) / 4, -3..9
  static const int clarity = 0x5c; // (b - 0x80) / 4, -5..5
  static const int midRangeSharpening = 0xf2; // (b - 0x80) / 4, -5..5
  static const int contrast = 0x110; // b - 0x80, -100..100
  static const int highlights = 0x11a;
  static const int shadows = 0x124;
  static const int whiteLevel = 0x12e;
  static const int blackLevel = 0x138;
  static const int saturation = 0x142;

  /// 8 channels x (hue, chroma, brightness), each b - 0x80, -100..100.
  static const int colorBlender = 0x14c; // 24 confirmed bytes

  /// 3 zones x (hue[12-bit], chroma, brightness).
  static const int colorGradingHigh = 0x170;
  static const int colorGradingMid = 0x174;
  static const int colorGradingShadow = 0x178;
  static const int colorGradingBlending = 0x180; // 0x80 + v (0..100 -> 0x80..0xca)
  static const int colorGradingBalance = 0x182; // 0x80 + v, -100..100

  /// End of the base block (before the 4-byte trailer).
  static const int baseEnd = 0x184;
  static const int trailer = 0x184; // 4 bytes: 00 00 00 00
  static const int baseSize = 0x184; // 388: header + base entries (trailer appended by generate)
}